import { Router } from 'express';

import type { ApiAuthRequest } from '../types/index.ts';

import { getDb } from '../db.ts';
import { sendEmailWithAttachment } from '../email.ts';
import { authenticateToken } from '../middleware/auth.ts';
import logger from '../utils/logger.ts';

const router = Router();

// CVs are routed to the HR department mailbox rather than individual IT personnel
const HR_EMAIL = 'hr@harisco.com';

interface SendCVRequestBody {
  candidateName: string;
  candidateEmail?: string;
  pdfBase64: string;
  fileName: string;
}

// POST /api/cv-generator/send
// Emails a generated CV PDF to the HR department mailbox (same SMTP as ticket notifications)
router.post('/send', authenticateToken, async (req: ApiAuthRequest<SendCVRequestBody>, res) => {
  const currentUser = req.user;
  if (!currentUser) {
    return res.status(401).json({ error: 'Unauthorized. User data missing.' });
  }

  const { candidateName, candidateEmail, pdfBase64, fileName } = req.body;

  if (!candidateName || !pdfBase64 || !fileName) {
    return res.status(400).json({ error: 'Missing required fields: candidateName, pdfBase64, fileName.' });
  }

  // Sanitize filename to ASCII-safe characters to avoid SMTP "WinAsi cannot encode"
  // errors on Windows caused by non-ASCII (e.g. Urdu/Arabic) characters in the
  // attachment filename. Printable ASCII only (a-zA-Z0-9._-); everything else -> '_'.
  const safeFileName = fileName.replace(/[^a-zA-Z0-9._-]/g, '_') || 'cv.pdf';

  try {
    const db = getDb();

    // Enforce screen access server-side — never trust the client's routing/UI gate
    if (currentUser.role !== 'it' && currentUser.role !== 'external') {
      const granted = await db.get(
        `SELECT so.user_id
         FROM screen_overrides so
         JOIN users u ON so.user_id = u.id
         WHERE so.screen_name = ? AND so.user_id = ? AND u.is_active = 1`,
        ['cv_generator', currentUser.id]
      );

      if (!granted) {
        return res.status(403).json({ error: 'You do not have access to the CV generator.' });
      }
    }

    // Recipients: the HR department mailbox
    const recipients = [HR_EMAIL];

    // Escape user-provided values to prevent HTML injection
    const escapeHtml = (s: string): string =>
      s
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#039;');

    const subject = `[Employee CV] ${escapeHtml(candidateName)}`;
    const body = `
<!DOCTYPE html>
<html>
<body style="font-family: 'Plus Jakarta Sans', sans-serif; line-height: 1.6; color: #333;">
  <h2 style="color: #0e529b;">Employee CV Generated</h2>
  <p>The CV generated through the CV Generator is attached to this email.</p>
  <table style="border-collapse: collapse; margin: 20px 0;">
    <tr><td style="padding: 4px 12px; border: 1px solid #ddd;"><strong>Employee Name:</strong></td><td style="padding: 4px 12px; border: 1px solid #ddd;">${escapeHtml(candidateName)}</td></tr>
    ${candidateEmail ? `<tr><td style="padding: 4px 12px; border: 1px solid #ddd;"><strong>Email:</strong></td><td style="padding: 4px 12px; border: 1px solid #ddd;">${escapeHtml(candidateEmail)}</td></tr>` : ''}
    <tr><td style="padding: 4px 12px; border: 1px solid #ddd;"><strong>Generated By:</strong></td><td style="padding: 4px 12px; border: 1px solid #ddd;">${escapeHtml(currentUser.name)}</td></tr>
    <tr><td style="padding: 4px 12px; border: 1px solid #ddd;"><strong>Date:</strong></td><td style="padding: 4px 12px; border: 1px solid #ddd;">${new Date().toLocaleString()}</td></tr>
  </table>
  <p>Please review the attached PDF for full details.</p>
  <p style="color: #999; font-size: 0.85rem; margin-top: 30px;">— Haris &amp; Co. HR Department</p>
</body>
</html>`;

    // Decode the base64 PDF payload into a Buffer so nodemailer attaches the real PDF
    // bytes (and emits a proper base64 Content-Transfer-Encoding). Passing the base64
    // string directly would make the attachment contain the literal base64 text,
    // which email clients then fail to decode as a PDF ("decoding error").
    const pdfBuffer = Buffer.from(pdfBase64, 'base64');
    if (!pdfBuffer.length || pdfBuffer[0] !== 0x25 || pdfBuffer[1] !== 0x50) {
      // 0x25 'P' 0x50 'D' — minimal PDF magic check ("PDF" is '%' + 70)
      return res.status(400).json({ error: 'Invalid PDF data received.' });
    }

    let sentCount = 0;
    const errors: string[] = [];

    for (const email of recipients) {
      const sent = await sendEmailWithAttachment(email, subject, body, [
        {
          filename: safeFileName,
          content: pdfBuffer,
          contentType: 'application/pdf',
        },
      ]).catch((err: unknown) => {
        logger.error(`[cv-generator] Failed to email CV to ${email}:`, err);
        errors.push(email);
        return false;
      });

      if (sent) sentCount++;
    }

    if (sentCount === 0) {
      logger.error(`[cv-generator] CV email to ${HR_EMAIL} failed.`);
      return res.status(500).json({ error: 'Failed to send CV email to HR.' });
    }

    logger.info(`[cv-generator] CV for ${candidateName} emailed to HR (${HR_EMAIL}).`);

    return res.json({
      success: true,
      sentCount,
      totalRecipients: recipients.length,
      errors: errors.length > 0 ? errors : undefined,
    });
  } catch (err) {
    logger.error('[cv-generator] Failed to process CV email:', err);
    return res.status(500).json({ error: 'Failed to send CV email.' });
  }
});

export default router;
